import {chromium,expect} from '@playwright/test';
import {writeFile,mkdir} from 'node:fs/promises';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1500,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
let generations=0;
// Browser QA never submits a paid question, even if a click regresses.
await page.route('**/api/questions',route=>{if(route.request().method()==='POST'){generations++;return route.abort();}return route.continue();});
const out='var/verification/reader3-browser';await mkdir(out,{recursive:true});
try{
await page.goto('http://127.0.0.1:8604');
await page.locator('.text-line').first().waitFor();
await page.locator('.session').filter({hasText:'attention.pdf'}).first().click();
await expect(page.locator('#document-title')).toHaveText('attention.pdf');
await expect(page.locator('#quick-note')).toBeVisible();await expect(page.locator('#quick-note')).toBeEnabled();
await expect(page.locator('#model-select')).toBeVisible();
await page.locator('#quick-note').click();
await page.locator('#note-body').fill('PAPER-003：常驻入口保存的个人理解。');
await page.locator('#save-note').click();
await expect(page.locator('#note-status')).toHaveText('已保存');
await page.reload();await page.locator('.text-line').first().waitFor();
await page.locator('#notes-tab').click();
await expect(page.locator('.note').first()).toContainText('常驻入口');
await page.locator('#chat-tab').click();
await page.locator('#model-select').selectOption('gemini-2.5-flash');
await page.locator('#model-settings').click();
await expect(page.locator('#web-search')).toBeEnabled();
await page.locator('#input-mode').selectOption('pdf');
await page.locator('#output-limit').fill('4096');
await page.locator('#save-settings').click();
await expect(page.locator('#settings-status')).toContainText('已保存');
await page.reload();await page.locator('.text-line').first().waitFor();
await expect(page.locator('#model-select')).toHaveValue('gemini-2.5-flash');
await page.locator('#model-settings').click();
await expect(page.locator('#input-mode')).toHaveValue('pdf');
await expect(page.locator('#output-limit')).toHaveValue('4096');
await page.locator('#model-select').selectOption('deepseek-flash');
await expect(page.locator('#web-search')).toBeDisabled();
await expect(page.locator('#input-mode')).toHaveValue('text');
await page.locator('#model-settings').click();
await page.locator('.cite').first().click();
await expect(page.locator('.highlight').first()).toBeVisible();
await page.locator('#zoom').selectOption('1');
await expect(page.locator('#pdf-page')).toHaveAttribute('data-zoom','1');
const before=await page.locator('.highlight').first().boundingBox();
await page.locator('#zoom').selectOption('1.5');
await expect(page.locator('#pdf-page')).toHaveAttribute('data-zoom','1.5');
const after=await page.locator('.highlight').first().boundingBox();
if(Math.abs(after.width/before.width-1.5)>.04)throw new Error('highlight scaling');
await page.locator('#zoom').selectOption('1');
const line=page.locator('.text-line').filter({hasText:'sub-layer in the decoder stack to prevent positions'}).first();
await line.scrollIntoViewIfNeeded();const box=await line.boundingBox();
await page.mouse.move(box.x+2,box.y+box.height/2);await page.mouse.down();
await page.mouse.move(box.x+Math.min(box.width-2,310),box.y+box.height/2,{steps:25});await page.mouse.up();
await expect(page.locator('#selection-bar')).toBeVisible();
await expect(page.locator('#discussion-scope')).toHaveValue('selection');
await page.locator('#selection-note').click();
await expect(page.locator('#note-context')).toContainText('decoder');
await page.locator('#note-body').fill('PAPER-003：实际鼠标选区笔记');await page.locator('#save-note').click();
await expect(page.locator('#note-status')).toHaveText('已保存');
await page.screenshot({path:out+'/notes-and-selection.png'});
await page.locator('#chat-tab').click();await page.locator('#clear-selection').click();
await expect(page.locator('#discussion-scope')).toHaveValue('paper');
await page.screenshot({path:out+'/reader.png'});
if(errors.length)throw new Error(errors.join('\n'));
if(generations)throw new Error('Unexpected attempted model call');
await writeFile(out+'/result.json',JSON.stringify({passed:true,paid_calls:0,checks:['visible notes','note reload','model switch','capability restrictions','settings reload','real selection and nearby toolbar','scope reset','citation scale']},null,2));
console.log('PAPER-003 browser checks passed, zero generation attempts.');
}catch(e){await page.screenshot({path:out+'/failure.png'});console.log(errors);throw e;}finally{await browser.close();}
