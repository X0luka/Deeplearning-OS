import {chromium,expect} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1600,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const base=process.env.PAPER_TEST_URL||'http://127.0.0.1:8603';
const out='var/verification/browser';await mkdir(out,{recursive:true});
try{
  await page.goto(base);
  await page.locator('.text-line').first().waitFor();
  await expect(page.locator('#document-title')).toHaveText('attention.pdf');
  await page.locator('#zoom').selectOption('1');
  await expect(page.locator('#pdf-page')).toHaveAttribute('data-zoom','1');
  await page.screenshot({path:out+'/01-reader.png'});
  await page.locator('.cite').first().click();
  await expect(page.locator('#pdf-page')).toHaveAttribute('data-page','3');
  await expect(page.locator('.highlight').first()).toBeVisible();
  const old=await page.locator('.highlight').first().boundingBox();
  await page.locator('#zoom').selectOption('1.5');
  await expect(page.locator('#pdf-page')).toHaveAttribute('data-zoom','1.5');
  const scaled=await page.locator('.highlight').first().boundingBox();
  if(Math.abs(scaled.width/old.width-1.5)>0.03)throw new Error('Citation highlight does not scale with PDF');
  await page.screenshot({path:out+'/02-citation-zoom.png'});
  await page.locator('#zoom').selectOption('1');
  await expect(page.locator('#pdf-page')).toHaveAttribute('data-zoom','1');
  const line=page.locator('.text-line').filter({hasText:'sub-layer in the decoder stack to prevent positions'}).first();
  await line.scrollIntoViewIfNeeded();
  const box=await line.boundingBox();
  await page.mouse.move(box.x+2,box.y+box.height/2);
  await page.mouse.down();
  await page.mouse.move(box.x+Math.min(box.width-2,310),box.y+box.height/2,{steps:25});
  await page.mouse.up();
  await expect(page.locator('#selection-bar')).toBeVisible();
  const selected=await page.locator('#question-selection').textContent();
  if(!selected.includes('decoder'))throw new Error('Mouse selection lost selected text');
  await page.locator('#selection-note').click();
  await page.locator('#note-body').fill('浏览器验证：残差与遮罩的区别需要结合上下文。');
  await page.locator('#save-note').click();
  await expect(page.locator('#note-status')).toHaveText('已保存');
  await expect(page.locator('.note').first()).toContainText(selected);
  await page.locator('.note').first().getByRole('button',{name:'编辑笔记'}).click();
  await page.locator('#note-body').fill('浏览器验证：修改后的个人笔记。');
  await page.locator('#save-note').click();
  await expect(page.locator('.note').first()).toContainText('修改后的个人笔记');
  await page.reload();
  await expect(page.locator('#pdf-page')).toHaveAttribute('data-page','3');
  await page.locator('#notes-tab').click();
  await expect(page.locator('.note').first()).toContainText('修改后的个人笔记');
  await expect(page.locator('.note').first()).toContainText(selected);
  await page.screenshot({path:out+'/03-note-restored.png'});
  await page.locator('#chat-tab').click();
  await page.locator('#question').fill('未启用助手时不能产生调用');
  const blocked=page.waitForResponse(r=>r.url().endsWith('/api/questions')&&r.request().method()==='POST');
  await page.locator('#send').click();
  if((await blocked).status()!==409)throw new Error('Question ran without explicit model consent');
  await expect(page.locator('#notice')).toContainText('启用');
  await page.locator('#notice').click();
  await page.locator('#page-number').fill('5');
  await page.locator('#page-number').press('Enter');
  await page.locator('#page-number').blur();
  await expect(page.locator('#pdf-page')).toHaveAttribute('data-page','5');
  await page.locator('#zoom').selectOption('1.25');
  await expect(page.locator('#pdf-page')).toHaveAttribute('data-zoom','1.25');
  await page.reload();
  await expect(page.locator('#pdf-page')).toHaveAttribute('data-page','5');
  await expect(page.locator('#pdf-page')).toHaveAttribute('data-zoom','1.25');
  if(errors.length)throw new Error(errors.join('\n'));
  await writeFile(out+'/result.json',JSON.stringify({passed:true,checks:['PDF original rendered','citation page and geometry','150% citation scaling','real mouse selection','selection note save/edit','page reload restores notes and location','model not called without consent'],model_calls:0},null,2));
  console.log('Browser checks passed; 0 model calls.');
}catch(error){await page.screenshot({path:out+'/failure.png'});console.error('PAGE ERRORS',errors);throw error;}finally{await browser.close();}
