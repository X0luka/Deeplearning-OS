"""Ports owned by the application, not by product implementations."""

from typing import Protocol


class Activity(Protocol):
    def snapshot(self) -> dict: ...
    def set_state(self, state: str) -> None: ...
    async def run(self, operation): ...
    async def drain(self) -> None: ...


class ProductAdapter(Protocol):
    async def health(self) -> dict: ...
    async def history(self, page: int, page_size: int) -> dict: ...
    async def detail(self, identity: int) -> dict: ...
    async def query(self, text: str) -> dict: ...
    async def changes(self, cursor: str | None) -> dict: ...


class Archive(Protocol):
    def activity(self, product: str) -> dict: ...
    def enqueue(self, product: str) -> int: ...
    def claim(self, products=None) -> dict | None: ...
    def finish(self, identity: int, state: str, error: str | None = None,
               imported: int = 0) -> None: ...
    def recover(self) -> None: ...
    def jobs(self) -> list[dict]: ...
    def job(self, identity: int) -> dict | None: ...
    def checkpoint(self, product: str) -> str | None: ...
    def apply(self, product: str, batch: dict, expected: str | None, generation=None) -> int: ...
    def product_ids(self) -> list[str]: ...
    def items(
        self, source: str, page: int, thread: str | None = None, product: str | None = None
    ) -> dict: ...
    def data_page(self, source="all", page=1, product=None, q=None, thread=None) -> dict: ...
    def detail(self, identity: int) -> dict | None: ...


class ProcessSupervisor(Protocol):
    async def ensure_product(self) -> None: ...
    async def ensure_worker(self) -> str: ...
    async def close(self) -> None: ...
