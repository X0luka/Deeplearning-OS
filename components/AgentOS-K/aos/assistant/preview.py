"""Loopback preview transport sharing an existing product's data and write checks."""
from contextlib import asynccontextmanager
from urllib.parse import urlsplit

import httpx
from fastapi import FastAPI, Request
from fastapi.responses import JSONResponse, Response, StreamingResponse

HOP_HEADERS = {"connection", "keep-alive", "proxy-authenticate", "proxy-authorization",
               "te", "trailer", "transfer-encoding", "upgrade"}


def create_preview(upstream, preview_token, transport=None, assistant_host="http://127.0.0.1:8777"):
    address = urlsplit(upstream)
    if address.scheme != "http" or address.hostname not in {"127.0.0.1", "localhost"} or address.username:
        raise ValueError("preview_requires_loopback")
    client = httpx.AsyncClient(trust_env=False, follow_redirects=False,
                              timeout=httpx.Timeout(60, connect=5), transport=transport)

    @asynccontextmanager
    async def lifespan(app):
        yield
        await client.aclose()

    app = FastAPI(lifespan=lifespan)

    @app.api_route("/{path:path}", methods=["GET", "HEAD", "POST", "PUT", "PATCH", "DELETE", "OPTIONS"])
    async def forward(request: Request, path: str):
        # Preserve the browser Host/Origin pair; the product still checks its CSRF token.
        if request.url.hostname not in {"127.0.0.1", "localhost", "testserver"}:
            return JSONResponse({"detail": "invalid_host"}, status_code=400)
        if request.headers.get("origin") and request.headers["origin"].rstrip("/") != str(request.base_url).rstrip("/"):
            return JSONResponse({"detail": "origin_rejected"}, status_code=403)
        headers = {k: v for k, v in request.headers.items() if k.lower() not in HOP_HEADERS | {"x-aos-preview-token", "x-aos-preview-host", "accept-encoding"}}
        headers["x-aos-preview-token"] = preview_token()
        headers["x-aos-preview-host"] = assistant_host
        headers["accept-encoding"] = "identity"
        query = ("?" + request.url.query) if request.url.query else ""
        target = upstream.rstrip("/") + "/" + path + query
        try:
            response = await client.send(client.build_request(request.method, target,
                headers=headers, content=request.stream()), stream=True)
        except httpx.HTTPError:
            return JSONResponse({"detail": "product_unavailable"}, status_code=503)
        outgoing = {k: v for k, v in response.headers.items() if k.lower() not in HOP_HEADERS}
        # URLs generated by the product use the preserved browser Host.
        outgoing["cache-control"] = "no-store"
        async def chunks():
            try:
                async for chunk in response.aiter_raw():
                    yield chunk
            finally:
                await response.aclose()
        if request.method == "HEAD":
            await response.aclose()
            return Response(status_code=response.status_code, headers=outgoing)
        return StreamingResponse(chunks(), status_code=response.status_code, headers=outgoing)

    return app
